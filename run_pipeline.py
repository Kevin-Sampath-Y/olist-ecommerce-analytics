"""
Run the whole project end to end:

    python run_pipeline.py                 # needs real CSVs in data/raw/
    python run_pipeline.py --synthetic     # no Kaggle account? generate demo data first
"""
from __future__ import annotations

import argparse
import time

from src import analysis, bi_export, build_database, charts, config, dashboard, report, run_sql


def step(title: str):
    print(f"\n== {title}")
    return time.time()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", action="store_true", help="generate demo data if data/raw is empty")
    ap.add_argument("--orders", type=int, default=40_000, help="orders to generate with --synthetic")
    args = ap.parse_args()
    t0 = time.time()

    missing = [f for f in config.CSV_FILES.values() if not (config.RAW_DIR / f).exists()]
    if missing and args.synthetic:
        t = step("0/6 Generating synthetic demo data")
        from src.generate_synthetic_data import generate
        config.RAW_DIR.mkdir(parents=True, exist_ok=True)
        for name, df in generate(args.orders).items():
            df.to_csv(config.RAW_DIR / f"{name}.csv", index=False)
        (config.RAW_DIR / "_SYNTHETIC_DATA.txt").write_text("Generated by src/generate_synthetic_data.py, not real Olist data.\n")
        print(f"   done in {time.time() - t:.1f}s")

    t = step("1/6 Building SQLite database");  build_database.build();          print(f"   {time.time() - t:.1f}s")
    t = step("2/6 Running SQL analysis");      sql = run_sql.run_all();         print(f"   {time.time() - t:.1f}s")
    t = step("3/6 Statistics and modelling");  ins = analysis.run(sql);         print(f"   {time.time() - t:.1f}s")
    t = step("4/6 Creating charts");           charts.make_all(sql, ins);       print(f"   {time.time() - t:.1f}s")
    t = step("5/6 Building dashboard");        print("  ", dashboard.build(sql, ins))
    t = step("6/6 Writing report + BI exports"); report.write(sql, ins); bi_export.export()
    print(f"\nAll done in {time.time() - t0:.0f}s. Open reports/dashboard.html")


if __name__ == "__main__":
    main()
